import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({args:['--use-angle=d3d11']});
const page=await browser.newPage({viewport:{width:1280,height:900},hasTouch:true});
const errors=[],mediaRequests=[];
await fs.mkdir('artifacts/journey',{recursive:true});
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error'||m.text().includes('buffers too small'))errors.push(m.text())});
// The hero's dust-impact clip is the one sanctioned video; anything else (e.g. the desolve.mp4 reference) must never load.
page.on('request',r=>{if(/\.(mp4|webm)(\?|$)/.test(r.url())&&!r.url().endsWith('/media/dust-impact.mp4'))mediaRequests.push(r.url())});
try{
 await page.goto('http://localhost:3001',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>Number(document.querySelector('.journey-canvas')?.dataset.fluidTriangles)>0);
 assert.deepEqual(errors,[]);
 const initial=await page.locator('.journey-canvas').evaluate(e=>({...e.dataset}));
 assert.equal(initial.fluidSpeed,'2.1');
 await page.waitForFunction(t=>Number(document.querySelector('.journey-canvas').dataset.fluidTime)>t+.5,Number(initial.fluidTime));
 await page.screenshot({path:'artifacts/journey/volume-hero.png'});
 await page.evaluate(()=>window.scrollTo(0,document.querySelector('#services').getBoundingClientRect().top+scrollY+120));
 await page.waitForTimeout(2500);
 await page.screenshot({path:'artifacts/journey/volume-services.png'});
 assert.equal(await page.locator('.services-heading').evaluate(e=>getComputedStyle(e).mixBlendMode),'difference');
 assert.equal(await page.locator('main').evaluate(e=>getComputedStyle(e).zIndex),'auto');
 assert.equal(await page.locator('.box-foreground').evaluate(e=>getComputedStyle(e).zIndex),'100');
 await page.mouse.move(450,550);
 await page.waitForFunction(()=>Number(document.querySelector('.journey-canvas').dataset.fluidHover)>.65);
 await page.screenshot({path:'artifacts/journey/volume-hover.png'});
 await page.mouse.move(0,0);
 await page.waitForFunction(()=>Number(document.querySelector('.journey-canvas').dataset.fluidHover)<.1);
 await page.evaluate(()=>document.querySelector('.journey-canvas').style.zIndex='200');
 await page.screenshot({path:'artifacts/journey/volume-study-a.png'});
 await page.waitForTimeout(2000);
 await page.screenshot({path:'artifacts/journey/volume-study-b.png'});
 await page.evaluate(()=>document.querySelector('.journey-canvas').style.removeProperty('z-index'));
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(1000);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'artifacts/journey/volume-mobile.png'});
 const final=await page.locator('.journey-canvas').evaluate(e=>({...e.dataset}));
 assert.ok(Number(final.fluidScrollPhase)>.1);
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForFunction(()=>document.querySelectorAll('canvas').length===0);
 assert.deepEqual(errors,[]);assert.deepEqual(mediaRequests,[]);
 await fs.writeFile('artifacts/journey/volume-verification.json',JSON.stringify({initial,final,errors,mediaRequests},null,2));
 console.log('PASS: real-time geometry updates, hover/recovery, mobile, reduced-motion cleanup, no video requests besides the hero dust clip, no browser errors');
}finally{await browser.close()}
